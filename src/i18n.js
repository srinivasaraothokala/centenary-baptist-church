// ── State ────────────────────────────────────────────────────
let currentLang = localStorage.getItem('cbc_lang') || 'en';

// ── Public: get current language ────────────────────────────
export function getCurrentLang() {
  return currentLang;
}

// ── Public: translate a key ──────────────────────────────────
export function t(key, fallbackLang = 'en') {
  const dict = translations[currentLang] || translations[fallbackLang];
  return dict[key] !== undefined ? dict[key] : (translations[fallbackLang][key] || key);
}

// ── Public: set language ─────────────────────────────────────
export function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('cbc_lang', lang);

  // Update <html lang="...">
  const htmlRoot = document.getElementById('html-root');
  if (htmlRoot) htmlRoot.setAttribute('lang', lang);

  // Update all data-i18n elements in the static DOM
  updateDOM();

  // Update switcher active state
  updateSwitcherUI();

  // Notify JS-rendered components to re-render
  window.dispatchEvent(new CustomEvent('langChange', { detail: { lang } }));
}

// ── Internal: update static data-i18n elements ───────────────
function updateDOM() {
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val && val !== key) {
      el.innerHTML = val;
    }
  });
}

// ── Internal: update switcher active highlight ───────────────
function updateSwitcherUI() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const isActive = btn.getAttribute('data-lang') === currentLang;
    btn.classList.toggle('active', isActive);
  });
}

// ── Public: initialize i18n (call on DOMContentLoaded) ───────
export function initI18n() {
  // Wire click events onto lang-btn buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      setLanguage(btn.getAttribute('data-lang'));
    });
  });

  // Apply stored/default language immediately
  setLanguage(currentLang);
}
